#! python3
"""
Build the WLCA package for Rhino 8 (Windows): WLCA.rhp + the Python scripts + toolbar -> a .yak file for the
Package Manager. Drafted by an AI agent (Claude) - review before trusting.

Needs only Windows and Rhino 8: the plug-in is compiled with the .NET Framework C# compiler that ships with Windows,
against Rhino's own RhinoCommon.dll, and packed with Rhino's Yak.exe. No .NET SDK or internet access.

    python build_package.py --config my_package.json        (or run it from Rhino's script editor)

Config (all optional except name / version):
    {"name": "WLCA",                 Package Manager name (letters, digits, '-', '_', '.')
     "title": "WLCA",                plug-in and dialog title, e.g. "Office WLCA"
     "version": "0.1.0",             0.1.0-beta for a pre-release
     "authors": ["..."], "company": "...", "description": "...", "url": "https://...",
     "icon": "path/to/icon.png",     square PNG for the Package Manager
     "office_settings": "X:/shared/WLCA/Settings/wlca_office_settings.json",   default settings file for every user
     "out": "dist"}                  where the .yak goes (a folder, e.g. a shared Package Manager source)
Relative paths are read from the config file's folder.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CARBON = os.path.dirname(HERE)
RHINO = os.environ.get("RHINO8_SYSTEM", r"C:\Program Files\Rhino 8\System")
CSC = os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "Microsoft.NET", "Framework64", "v4.0.30319", "csc.exe")
SCRIPTS = [("rhino_ui", "wlca_dialog.py"), ("rhino_ui", "wlca_state.py"),
           ("takeoff", "wlca_core.py"), ("takeoff", "wlca_massing_takeoff.py"), ("takeoff", "wlca_plan_rhino.py"),
           ("takeoff", "wlca_plan_extract.py"), ("calc", "wlca_calc_template.py"), ("calc", "wlca_dashboard.py")]
SOURCES = ["WlcaPlugin.ai.cs", "WlcaCommand.ai.cs"]


def load_config(path):
    cfg = {"name": "WLCA", "title": "WLCA", "version": "0.1.0", "authors": ["WLCA contributors"], "company": "",
           "description": "Concept-stage whole life carbon assessment (RICS PS 2nd ed.) from a Rhino massing model: "
                          "take-off, Excel calculation workbook and dashboard.",
           "url": "https://github.com/wxcchuck/RhinoAI-Carbon/tree/rhino-9.x/carbon", "icon": "", "office_settings": "",
           "out": os.path.join(HERE, "dist")}
    base = HERE
    if path:
        base = os.path.dirname(os.path.abspath(path))
        with open(path, encoding="utf-8") as f:
            cfg.update(json.load(f))
    for k in ("icon", "out"):
        if cfg.get(k) and not os.path.isabs(cfg[k]):
            cfg[k] = os.path.normpath(os.path.join(base, cfg[k]))
    return cfg


def numeric_version(v):
    """'0.1.0-beta' -> '0.1.0.0' for the assembly version."""
    core = v.split("-")[0].split("+")[0].split(".")
    return ".".join((core + ["0"] * 4)[:4])


def cs(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def assembly_info(cfg):
    return """// Generated by build_package.py - do not edit.
using System.Reflection;
using Rhino.PlugIns;

[assembly: AssemblyTitle("{t}")]
[assembly: AssemblyProduct("{t}")]
[assembly: AssemblyDescription("{d}")]
[assembly: AssemblyCompany("{c}")]
[assembly: AssemblyVersion("{n}")]
[assembly: AssemblyFileVersion("{n}")]
[assembly: AssemblyInformationalVersion("{v}")]
[assembly: PlugInDescription(DescriptionType.Organization, "{c}")]
[assembly: PlugInDescription(DescriptionType.WebSite, "{u}")]
""".format(t=cs(cfg["title"]), d=cs(cfg["description"]), c=cs(cfg.get("company") or cfg["title"]),
           n=numeric_version(cfg["version"]), v=cs(cfg["version"]), u=cs(cfg.get("url") or ""))


def manifest(cfg, icon_name):
    lines = ["---", "name: %s" % cfg["name"], "version: %s" % cfg["version"], "authors:"]
    lines += ["- %s" % a for a in cfg.get("authors") or ["WLCA contributors"]]
    lines += ["description: >", "  %s" % cfg["description"].replace("\n", " ")]
    if cfg.get("url"):
        lines.append("url: %s" % cfg["url"])
    if icon_name:
        lines.append("icon: %s" % icon_name)
    lines += ["keywords:", "- carbon", "- wlca", "- rics", "- embodied"]
    return "\n".join(lines) + "\n"


def run(cmd, cwd):
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError("%s failed:\n%s\n%s" % (os.path.basename(cmd[0]), r.stdout, r.stderr))
    return r.stdout


def build(cfg):
    import tempfile
    stage = tempfile.mkdtemp(prefix="wlca_pkg_")      # outside synced folders (OneDrive holds folders open)
    # 1 plug-in
    info = os.path.join(HERE, "AssemblyInfo.g.cs")
    with open(info, "w", encoding="utf-8") as f:
        f.write(assembly_info(cfg))
    run([CSC, "/nologo", "/target:library", "/optimize+", "/out:" + os.path.join(stage, "WLCA.rhp"),
         "/r:" + os.path.join(RHINO, "RhinoCommon.dll")] + [os.path.join(HERE, s) for s in SOURCES] + [info], HERE)
    # 2 scripts, toolbar, package settings
    for folder, name in SCRIPTS:
        shutil.copy2(os.path.join(CARBON, folder, name), stage)
    shutil.copy2(os.path.join(HERE, "WLCA.rui"), stage)
    pkg = {"name": cfg["title"], "version": cfg["version"]}
    if cfg.get("office_settings"):
        pkg["office_settings"] = cfg["office_settings"]
    with open(os.path.join(stage, "wlca_package.json"), "w", encoding="utf-8") as f:
        json.dump(pkg, f, indent=1)
    icon_name = ""
    if cfg.get("icon"):
        icon_name = "icon" + os.path.splitext(cfg["icon"])[1].lower()
        shutil.copy2(cfg["icon"], os.path.join(stage, icon_name))
    with open(os.path.join(stage, "manifest.yml"), "w", encoding="utf-8") as f:
        f.write(manifest(cfg, icon_name))
    # 3 .yak (Windows only: the dialog uses Windows paths and Excel)
    run([os.path.join(RHINO, "Yak.exe"), "build", "--platform", "win"], stage)
    yaks = [f for f in os.listdir(stage) if f.endswith(".yak")]
    if not yaks:
        raise RuntimeError("Yak.exe made no .yak file")
    os.makedirs(cfg["out"], exist_ok=True)
    dst = os.path.join(cfg["out"], yaks[0])
    shutil.copy2(os.path.join(stage, yaks[0]), dst)
    shutil.rmtree(stage, ignore_errors=True)
    return dst


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--config", help="package config json")
    a = ap.parse_args(argv)
    path = build(load_config(a.config))
    print("Built", path)
    return path


def pick_config_in_rhino():
    """Run from Rhino's script editor (no command line): ask for the config file."""
    try:
        import Rhino.UI
    except ImportError:
        return None
    dlg = Rhino.UI.OpenFileDialog()
    dlg.Title = "WLCA package config (.json)"
    dlg.Filter = "Package config (*.json)|*.json"
    return dlg.FileName if dlg.ShowOpenDialog() else None


if __name__ == "__main__":
    if len(sys.argv) > 1:
        main(sys.argv[1:])
    else:
        cfg_path = pick_config_in_rhino()
        main(["--config", cfg_path] if cfg_path else [])
